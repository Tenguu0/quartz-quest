/** Parse a level map into solids, spikes, crystals, spawns and pads. */
export function parseLevel(level) {
  const solids = new Set();
  const spikes = [];
  const crystals = [];
  const pads = [];
  let player = null;
  let portal = null;
  const slimes = [];
  level.map.forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      const ch = row[x];
      const key = `${x},${y}`;
      if (ch === '#') solids.add(key);
      else if (ch === '^') spikes.push({ x, y });
      else if (ch === 'C') crystals.push({ x, y, taken: false });
      else if (ch === 'P') player = { x, y };
      else if (ch === 'X') portal = { x, y };
      else if (ch === 'S') slimes.push({ x, y });
      else if (ch === 'B') pads.push({ x, y });
    }
  });
  return { solids, spikes, crystals, pads, player, portal, slimes };
}
